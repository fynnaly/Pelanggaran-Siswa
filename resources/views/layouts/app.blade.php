    <!-- Lucide Icons -->
    <script src="{{ asset('vendor/lucide/lucide.min.js') }}"></script>
    <script>
        if (window.lucide) {
            lucide.createIcons();
            // Re-create icons when Alpine updates DOM
            document.addEventListener('alpine:updated', () => lucide.createIcons());
        }
